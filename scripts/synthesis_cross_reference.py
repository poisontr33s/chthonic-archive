def build_corpus_claims() -> list[dict]:
    """Claims whose source is the ANKH corpus files, not the archive index."""
    claims: list[dict] = []

    def claim(id: str, section: str, desc: str, pattern: str, files: list[str] | None = None):
        claims.append({
            "id": id, "section": section,
            "description": desc, "pattern": pattern,
            "files": files,  # None = search all corpus files
        })

    # Alpha Directives — names originate in corpus, not archive
    claim("AD-WEPET-ER", "III",
          "Alpha Directive WEPET-ER in corpus", r"WEPET.ER")
    claim("AD-TINKU", "III",
          "Alpha Directive TINKU in corpus", r"\bTINKU\b")
    claim("AD-SEKHMET", "III",
          "Alpha Directive SEKHMET in corpus", r"\bSEKHMET\b")
    claim("AD-AMMIT", "III",
          "Alpha Directive AMMIT in corpus", r"\bAMMIT\b")
    claim("AD-PACHAKUTI", "III",
          "Alpha Directive PACHAKUTI in corpus", r"\bPACHAKUTI\b")
    claim("AD-DESPACHO", "III",
          "Alpha Directive DESPACHO in corpus", r"\bDESPACHO\b")

    return claims


def run_corpus_cross_reference(repo_root: Path) -> dict:
    """Grep corpus files for corpus-sourced claims."""
    claims = build_corpus_claims()
    results: list[dict] = []

    for c in claims:
        target_files = c["files"] or CORPUS_FILES
        found_in: list[str] = []
        for rel in target_files:
            fpath = repo_root / rel
            if not fpath.is_file():
                continue
            text = fpath.read_text(encoding="utf-8", errors="replace")
            if re.search(c["pattern"], text, re.IGNORECASE):
                found_in.append(rel)

        passed = len(found_in) > 0
        results.append({
            "id": c["id"],
            "section": c["section"],
            "type": "corpus-grep",
            "description": c["description"],
            "verdict": "LOSSLESS" if passed else "UNVERIFIED",
            "detail": f"/{c['pattern']}/ found in {len(found_in)} file(s)"
                      + (f": {', '.join(found_in[:3])}" if found_in else ""),
        })

    return {
        "total_claims": len(results),
        "lossless": sum(1 for r in results if r["verdict"] == "LOSSLESS"),
        "unverified": sum(1 for r in results if r["verdict"] == "UNVERIFIED"),
        "results": results,
    }


