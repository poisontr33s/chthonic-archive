def format_report(
    archive_results: dict,
    corpus_results: dict,
    corpus_existence: dict,
) -> str:
    """Format human-readable cross-reference report."""
    lines: list[str] = []
    lines.append("=" * 72)
    lines.append("  SYNTHESIS CROSS-REFERENCE REPORT")
    lines.append("=" * 72)

    # --- Corpus file existence ---
    lines.append("")
    lines.append(f"Corpus Files: {corpus_existence['found']}/{corpus_existence['total']} found")
    if corpus_existence["missing"] > 0:
        for r in corpus_existence["results"]:
            if not r["exists"]:
                lines.append(f"  MISSING: {r['path']}")

    # --- Archive-index claims ---
    lines.append("")
    lines.append(f"Archive-Index Claims: {archive_results['lossless']}/{archive_results['total_claims']} LOSSLESS")
    for r in archive_results["results"]:
        mark = "✓" if r["verdict"] == "LOSSLESS" else "✗"
        lines.append(f"  {mark} [{r['id']}] {r['description']}")
        lines.append(f"        {r['detail']}")

    # --- Corpus-grep claims ---
    lines.append("")
    lines.append(f"Corpus-Grep Claims: {corpus_results['lossless']}/{corpus_results['total_claims']} LOSSLESS")
    for r in corpus_results["results"]:
        mark = "✓" if r["verdict"] == "LOSSLESS" else "✗"
        lines.append(f"  {mark} [{r['id']}] {r['description']}")
        lines.append(f"        {r['detail']}")

    # --- Subjective sections ---
    lines.append("")
    lines.append(f"Subjective Sections: {len(SUBJECTIVE_SECTIONS)} classified")
    for s in SUBJECTIVE_SECTIONS:
        lines.append(f"  ◌ [{s['id']}] Section {s['section']}: {s['description']}")
        lines.append(f"        Reason: {s['reason']}")

    # --- Summary ---
    total_lossless = archive_results["lossless"] + corpus_results["lossless"]
    total_claims = archive_results["total_claims"] + corpus_results["total_claims"]
    total_unverified = archive_results["unverified"] + corpus_results["unverified"]
    lines.append("")
    lines.append("-" * 72)
    lines.append(f"  TOTAL: {total_lossless}/{total_claims} LOSSLESS, "
                 f"{total_unverified} UNVERIFIED, "
                 f"{len(SUBJECTIVE_SECTIONS)} SUBJECTIVE")
    lines.append("-" * 72)

    return "\n".join(lines)


