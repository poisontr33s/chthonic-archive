# =============================================================================
# Corpus file existence check
# =============================================================================

def check_corpus_existence(repo_root: Path) -> dict:
    """Verify that all 15 declared corpus files actually exist."""
    results: list[dict] = []
    for rel in CORPUS_FILES:
        fpath = repo_root / rel
        exists = fpath.is_file()
        results.append({
            "id": f"FILE-{Path(rel).stem}",
            "path": rel,
            "exists": exists,
        })
    missing = [r for r in results if not r["exists"]]
    return {
        "total": len(results),
        "found": len(results) - len(missing),
        "missing": len(missing),
        "results": results,
    }


