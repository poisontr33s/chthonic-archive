def build_claims() -> list[dict]:
    """Build the registry of testable claims from the synthesis.

    Each claim has:
        id:          unique label
        section:     synthesis section it appears in
        type:        acronym | heading | count | range | hierarchy
        description: what is being claimed
        test:        callable(index_data) -> (bool, str)
    """
    claims: list[dict] = []

    def claim(id: str, section: str, ctype: str, desc: str, test):
        claims.append({
            "id": id, "section": section, "type": ctype,
            "description": desc, "test": test,
        })

    # --- Helper closures ---

    def acronym_exists(acr: str):
        def _test(ix):
            found = acr in ix["acronym_registry"]
            return found, f"acronym '{acr}' {'found' if found else 'NOT found'} in registry"
        return _test

    def acronym_at_line(acr: str, line: int):
        def _test(ix):
            lines = ix["acronym_registry"].get(acr, [])
            found = line in lines
            return found, f"acronym '{acr}' at L{line}: {'YES' if found else 'NO'} (index has {lines})"
        return _test

    def heading_matches(line: int, pattern: str):
        def _test(ix):
            for s in ix["sections"]:
                if s["heading_line"] == line:
                    match = bool(re.search(pattern, s["raw_title"], re.IGNORECASE))
                    return match, f"L{line} title matches /{pattern}/: {'YES' if match else 'NO'} — actual: {s['raw_title'][:80]}"
            return False, f"No heading found at L{line}"
        return _test

    def heading_contains_word(pattern: str, min_matches: int = 1):
        def _test(ix):
            matches = [s for s in ix["sections"] if re.search(pattern, s["raw_title"], re.IGNORECASE)]
            ok = len(matches) >= min_matches
            return ok, f"/{pattern}/ matches {len(matches)} heading(s) (need >={min_matches})"
        return _test

    def total_headings(expected: int):
        def _test(ix):
            actual = ix["totals"]["headings"]
            return actual == expected, f"total headings: {actual} (expected {expected})"
        return _test

    def heading_census_level(level: str, expected: int):
        def _test(ix):
            actual = ix["heading_census"].get(level, 0)
            return actual == expected, f"{level}: {actual} (expected {expected})"
        return _test

    def total_lines(expected: int):
        def _test(ix):
            actual = ix["totals"]["lines"]
            return actual == expected, f"total lines: {actual} (expected {expected})"
        return _test

    def total_words_approx(expected: int, tolerance: float = 0.05):
        def _test(ix):
            actual = ix["totals"]["words"]
            ratio = abs(actual - expected) / max(expected, 1)
            ok = ratio <= tolerance
            return ok, f"total words: {actual} (expected ~{expected}, tolerance {tolerance*100:.0f}%)"
        return _test

    def acronym_count(expected: int):
        def _test(ix):
            actual = ix["totals"]["unique_acronyms"]
            return actual == expected, f"unique acronyms: {actual} (expected {expected})"
        return _test

    def section_body_range(heading_line: int, expected_start: int, expected_end: int):
        def _test(ix):
            for s in ix["sections"]:
                if s["heading_line"] == heading_line:
                    ok = s["body_start"] == expected_start and s["body_end"] == expected_end
                    return ok, f"L{heading_line} body: L{s['body_start']}–L{s['body_end']} (expected L{expected_start}–L{expected_end})"
            return False, f"No section at L{heading_line}"
        return _test

    def section_has_children(heading_line: int, min_children: int = 1):
        def _test(ix):
            for s in ix["sections"]:
                if s["heading_line"] == heading_line:
                    ok = s["children_count"] >= min_children
                    return ok, f"L{heading_line} children: {s['children_count']} (need >={min_children})"
            return False, f"No section at L{heading_line}"
        return _test

