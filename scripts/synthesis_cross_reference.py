def main() -> None:
    configure_utf8_output()
    repo = find_repo_root()

    parser = argparse.ArgumentParser(
        description="Cross-reference ANKH_SYNTHESIS_BASELINE.md claims against structural index and corpus files.",
    )
    parser.add_argument("--json", action="store_true", help="JSON output")
    parser.add_argument("--failures-only", action="store_true", help="Show only failures/unverified")
    parser.add_argument("--verbose", "-v", action="store_true")
    parser.add_argument("--quiet", "-q", action="store_true")
    args = parser.parse_args()

    logger = setup_logging(verbose=args.verbose, quiet=args.quiet)

    index_path = repo / INDEX_REL

    if not index_path.is_file():
        logger.error("Structural index not found: %s", index_path)
        logger.error("Run: uv run scripts/ssot_structural_extractor.py --update-index")
        sys.exit(2)

    archive_results = run_cross_reference(index_path)
    corpus_results = run_corpus_cross_reference(repo)
    corpus_existence = check_corpus_existence(repo)

    if args.json:
        combined = {
            "archive_claims": archive_results,
            "corpus_claims": corpus_results,
            "corpus_existence": corpus_existence,
            "subjective_sections": SUBJECTIVE_SECTIONS,
        }
        print(json.dumps(combined, indent=2))
    else:
        report = format_report(archive_results, corpus_results, corpus_existence)
        if args.failures_only:
            for line in report.split("\n"):
                if "✗" in line or "MISSING" in line or line.startswith("  ") and "UNVERIFIED" in line:
                    print(line)
                elif not line.startswith("  "):
                    print(line)
        else:
            print(report)

    total_unverified = archive_results["unverified"] + corpus_results["unverified"]
    sys.exit(1 if total_unverified > 0 else 0)


if __name__ == "__main__":
    main()
