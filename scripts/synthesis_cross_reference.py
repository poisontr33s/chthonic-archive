def run_cross_reference(index_path: Path) -> dict:
    """Load index, run all claims, return results."""
    with open(index_path, "r", encoding="utf-8") as f:
        ix = json.load(f)

    claims = build_claims()
    results: list[dict] = []

    for c in claims:
        passed, detail = c["test"](ix)
        results.append({
            "id": c["id"],
            "section": c["section"],
            "type": c["type"],
            "description": c["description"],
            "verdict": "LOSSLESS" if passed else "UNVERIFIED",
            "detail": detail,
        })

    return {
        "index_path": str(index_path),
        "total_claims": len(results),
        "lossless": sum(1 for r in results if r["verdict"] == "LOSSLESS"),
        "unverified": sum(1 for r in results if r["verdict"] == "UNVERIFIED"),
        "results": results,
    }


